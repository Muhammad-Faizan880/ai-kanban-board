// 1.1 Get Single Task by ID
export const getTaskById = async (req, res) => {
  try {
    const { id } = req.params;
    const task = await Task.findOne({ _id: id, user: req.user.userId });
    if (!task) {
      return res.status(404).json({ message: "Task not found" });
    }
    res.status(200).json({ task });
  } catch (error) {
    res.status(500).json({ message: "Failed to fetch task", error: error.message });
  }
};

// 2. Create task
export const createTask = async (req, res) => {
  try {
    const { title, description, status, priority, dueDate, subtasks, aiGenerated } = req.body;

    if (!title) {
      return res.status(400).json({ message: "Task title is required" });
    }

    const task = await Task.create({
      title,
      description: description || "",
      status: status || "TODO",
      priority: priority || "MEDIUM",
      dueDate: dueDate || new Date().toLocaleDateString("en-US", { month: "short", day: "numeric" }),
      subtasks: subtasks || [],
      aiGenerated: !!aiGenerated,
      user: req.user.userId,
    });

    res.status(201).json({ message: "Task created successfully", task });
  } catch (error) {
    res.status(500).json({ message: "Failed to create task", error: error.message });
  }
};

// 3. Update task status (Optimized for drag and drop)
export const updateTaskStatus = async (req, res) => {
  try {
    const { id } = req.params;
    const { status } = req.body;

    if (!["TODO", "IN_PROGRESS", "REVIEW", "DONE"].includes(status)) {
      return res.status(400).json({ message: "Invalid status" });
    }

    const task = await Task.findOneAndUpdate(
      { _id: id, user: req.user.userId },
      { status },
      { new: true }
    );

    if (!task) {
      return res.status(404).json({ message: "Task not found" });
    }

    res.status(200).json({ message: `Task moved to ${status}`, task });
  } catch (error) {
    res.status(500).json({ message: "Failed to update task status", error: error.message });
  }
};

