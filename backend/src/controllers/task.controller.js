// 6. AI Task Breakdown Generator
export const generateAITaskBreakdown = async (req, res) => {
  try {
    const { prompt } = req.body;

    if (!prompt || typeof prompt !== "string") {
      return res.status(400).json({ message: "Task description prompt is required" });
    }

    const apiKey = process.env.GEMINI_API_KEY;

    if (apiKey) {
      try {
        const response = await fetch(
          `https://generativelanguage.googleapis.com/v1beta/models/gemini-3.1-flash-lite:generateContent?key=${apiKey}`,
          {
            method: "POST",
            headers: { 
              "Content-Type": "application/json",
              "x-goog-api-key": apiKey
            },
            body: JSON.stringify({
              contents: [
                {
                  parts: [
                    {
                      text: `You are an expert Agile Scrum Master and Tech Lead.
The user wants to accomplish this task: "${prompt}"

Decompose this task into a structured technical plan.
Return ONLY a valid JSON object (no markdown code blocks, no backticks, no explanatory text) matching this schema:
{
  "title": "Short concise action title (max 7 words)",
  "description": "Clear explanation of goal and implementation approach (2 sentences)",
  "priority": "HIGH" | "MEDIUM" | "LOW",
  "estimatedTime": "e.g. 3 hours or 2 days",
  "subtasks": [
    { "title": "Specific step 1", "completed": false },
    { "title": "Specific step 2", "completed": false },
    { "title": "Specific step 3", "completed": false },
    { "title": "Specific step 4", "completed": false }
  ]
}`,
                    },
                  ],
                },
              ],
            }),
          }
        );

        if (response.ok) {
          const data = await response.json();
          let rawText = data?.candidates?.[0]?.content?.parts?.[0]?.text || "";
          rawText = rawText.replace(/```json/g, "").replace(/```/g, "").trim();
          const parsed = JSON.parse(rawText);

          return res.status(200).json({
            success: true,
            source: "gemini-ai",
            breakdown: parsed,
          });
        }
      } catch (geminiErr) {
        console.warn("Gemini call failed, falling back to heuristic engine:", geminiErr.message);
      }
    }

    // Fallback to Smart Heuristic Engine
    const breakdown = generateSmartHeuristicBreakdown(prompt);
    return res.status(200).json({
      success: true,
      source: "smart-engine",
      breakdown,
    });
  } catch (error) {
    res.status(500).json({ message: "AI decomposition failed", error: error.message });
  }
};
